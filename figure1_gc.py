def grid(ax, fills=(), rows=6, cols=8):
    ax.set_xlim(-0.1, 10.2); ax.set_ylim(rows + 0.1, -0.1); ax.axis("off")
    for r in range(rows):
        for c in range(cols):
            ax.add_patch(Rectangle((c, r), 1, 1, facecolor=fills.get((r, c), CELL), edgecolor="white", lw=0.8))


def endpoints():
    """Supplementary Figure 7: the evaluation endpoints a substrate-pair x condition matrix supports."""
    SW, SH = 7.0, 1.80
    pairs = pd.read_csv(OUT / "posthit_pair_support.csv")
    hits = pairs[pairs.m6 >= 0.20]
    fig = plt.figure(figsize=(SW, SH))
    kinds = ["optimisation", "general", "coverage", "this work"]
    titles = {"optimisation": "Optimisation", "general": "General conditions", "coverage": "Coverage",
              "this work": "This work: residual yield"}
    notes = {"coverage": "Pairs that a few conditions\ntake past a detection or\nyield threshold",
             "general": "One condition, best yield\naveraged over many pairs",
             "optimisation": "Successive experiments\nraise one reaction's yield",
             "this work": "Residual measured yield of\na fixed hit cohort\n"
                          f"({len(hits):,} hits, {hits.screen.nunique()} libraries)"}
    for j, kind in enumerate(kinds):
        x0 = 0.15 + j * 1.72
        fig.text((x0 + 0.02) / SW, (SH - 0.20) / SH, titles[kind], fontsize=LARGE, fontweight="bold", va="baseline")
        ax = inch_axes(fig, x0, SH - 1.13, 1.6, 0.84)
        if kind == "coverage":
            grid(ax, {(r, c): LIGHT for r in range(6) for c in (1, 4, 6)})
            for r in range(6):
                ax.plot(8.9, r + 0.5, "o", ms=5, mfc=BLUE if r != 2 else "white", mec=BLUE, mew=0.8)
        elif kind == "general":
            grid(ax, {(r, 3): BLUE for r in range(6)})
        elif kind == "optimisation":
            seq = [(2, 1), (2, 5), (2, 2), (2, 6)]
            grid(ax, {cell: BLUE for cell in seq})
            for k, (r, c) in enumerate(seq, 1):
                ax.text(c + 0.5, r + 0.55, str(k), ha="center", va="center", fontsize=SMALL, color="white")
        else:
            grid(ax, {(r, c): LIGHT for r in range(6) for c in (0, 2, 5)})
            for r, (c, g) in enumerate(zip([2, 6, 0, 7, 5, 3], [0.0, 1.3, 0.0, 1.7, 0.0, 0.8])):
                ax.plot(c + 0.5, r + 0.5, marker=(5, 1, 0), ms=6.5, color="black", mew=0.4)
                if g:
                    ax.add_patch(Rectangle((8.3, r + 0.25), g, 0.5, facecolor=ORANGE, edgecolor="none"))
        fig.text((x0 + 0.02) / SW, (SH - 1.23) / SH, notes[kind], fontsize=SMALL, va="top", linespacing=1.15)
    return fig


