def chem(text):
    """Formula digits as Arial subscripts through mathtext (Arial has no Unicode subscript digits)."""
    import re
    from presentation_gc import _FORMULA_PATTERN
    def sub(match):
        f = match.group()
        return "$\\mathregular{" + re.sub(r"(?<=[A-Za-z)\]])(\d+)", r"_{\1}", f) + "}$"
    return _FORMULA_PATTERN.sub(sub, text)


def inch_axes(fig, x, y, w, h):
    fw, fh = fig.get_size_inches()
    return fig.add_axes([x / fw, y / fh, w / fw, h / fh])


def product_smiles(aryl_halide, boronic_acid):
    rxn = AllChem.ReactionFromSmarts("[c:1][Br,Cl,I].[c:2]B(O)O>>[c:1]-[c:2]")
    products = {Chem.MolToSmiles(p[0]) for p in rxn.RunReactants((Chem.MolFromSmiles(aryl_halide),
                                                                   Chem.MolFromSmiles(boronic_acid)))}
    assert len(products) == 1, products
    return products.pop()


def example_master(E):
    """Return the expected SMILES and the ChemDraw master of the example pair (None if absent).

    A master that shows another pair is refused; Figure 1a and the TOC graphic both read it here."""
    expected = [E["sub_1_smiles"], E["sub_2_smiles"], product_smiles(E["sub_1_smiles"], E["sub_2_smiles"])]
    master = FIG / "example_pair_scheme.pdf"
    if not master.exists():
        return expected, None
    cdxml = (FIG / "example_pair_scheme.cdxml").read_text(encoding="utf-8")
    drawn = {Chem.MolToSmiles(m) for m in Chem.MolsFromCDXML(cdxml)}
    assert drawn == {Chem.MolToSmiles(Chem.MolFromSmiles(s)) for s in expected}, \
        "the ChemDraw master shows another pair; rerun tools/build_chemdraw_example_gc.py"
    return expected, master


def scheme_raster(E, fig):
    expected, master = example_master(E)
    if master is not None:
        # The ChemDraw master (tools/build_chemdraw_example_gc.py) at STRUCTURE_SCALE of its ACS 1996
        # size, rasterised at that scale so one raster pixel is one printed pixel.
        import pymupdf
        import xml.etree.ElementTree as ET
        from PIL import Image
        cdxml = (FIG / "example_pair_scheme.cdxml").read_text(encoding="utf-8")
        with pymupdf.open(master) as document:
            page = document[0]
            zoom = DPI * STRUCTURE_SCALE / 72
            pix = page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), alpha=True)
            raster = Image.frombytes("RGBA", [pix.width, pix.height], pix.samples)
            w, h = STRUCTURE_SCALE * page.rect.width / 72, STRUCTURE_SCALE * page.rect.height / 72
            # The master generator appends the arrow shaft and head after the three structures.
            paths = page.get_drawings()
            arrow = paths[-2]["rect"] | paths[-1]["rect"]
            fig._figure1_arrow_fraction = (arrow.x0 + arrow.x1) / (2 * page.rect.width)
        root = ET.fromstring(cdxml)
        label_size = float(root.attrib["LabelSize"])
        glyphs = [{"font_px": label_size * zoom, "text": "native atom labels", "role": "atom"}]
        for span in root.iter("s"):
            script = int(span.get("face", "0")) & (32 | 64)
            glyphs.append({"font_px": float(span.get("size", label_size)) * (0.75 if script else 1) * zoom,
                           "text": "".join(span.itertext()), "role": "subscript or charge" if script else "atom"})
        return raster, w, h, glyphs, master
    row = SimpleNamespace(reactant1_smiles=expected[0], reactant2_smiles=expected[1], product_smiles=expected[2])
    raster, lengths, glyphs, vector = scheme_drawing(row)
    fig._chemical_geometry_audit = [{"transformation": "Figure 1a example", "bond_lengths_px": lengths, "glyphs": glyphs}]
    return raster, raster.width / DPI, raster.height / DPI, glyphs, vector


def recipe_parts(D, condition):
    """The components of one condition, amounts dropped, in the order the recipe lists them."""
    import re
    recipe = D.loc[D.condition_id == condition, "recipe"].iloc[0]
    return [re.sub(r"\s*\([\d.]+\)$", "", part.strip()) for part in recipe.split(";")]


def panel_a(fig, E, D, vectors):
    heading = fig.text(0, 0, "A %s hit and the best recipe in its own library" % "Suzuki–Miyaura")
    raster, w, h, glyphs, vector = scheme_raster(E, fig)
    top = H - 0.62
    sx = inch_axes(fig, (W - w) / 2, top - h, w, h); sx.axis("off")
    image = sx.imshow(raster, interpolation="nearest")
    sx._chemical_font_audit = [(image, glyphs)]
    vectors.append((image, vector))
    hit_parts, best_parts = recipe_parts(D, E["hit_condition"]), recipe_parts(D, E["best_condition"])
    shared = []
    while hit_parts and best_parts and hit_parts[-1] == best_parts[-1]:
        shared.insert(0, hit_parts.pop()); best_parts.pop()
    assert shared, "the hit and the best recipe share no reaction medium"
    arrow_x = (W - w) / 2 + w * getattr(fig, "_figure1_arrow_fraction", 0.60)
    shared_text = fig.text(arrow_x / W, (top + 0.14) / H, chem(", ".join(shared)),
                           fontsize=SMALL, va="center", ha="center")
    y, step = top - h - 0.10, 0.19
    lines = [("o", "hit (%s), %.1f%%:  %s" % (E["hit_condition"], 100 * E["m6"], chem(", ".join(hit_parts)))),
             ((5, 1, 0), "library best (%s), %.1f%%:  %s" % (E["best_condition"], 100 * E["b"], chem(", ".join(best_parts))))]
    texts, markers = [], []
    for k, (marker, label) in enumerate(lines):
        yy = y - k * step
        texts.append(fig.text(0.5, yy / H, label, fontsize=SMALL, va="center", ha="left"))
        if marker == "o":
            symbol = Line2D([0], [yy / H], transform=fig.transFigure, ls="none", marker="o", ms=6,
                            mfc="none", mec="black", mew=1.0)
        else:
            symbol = Line2D([0], [yy / H], transform=fig.transFigure, ls="none", marker=marker, ms=7.5,
                            color="black", mew=0.4)
        fig.add_artist(symbol); markers.append(symbol)
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    for text, symbol in zip(texts, markers):
        text_width = text.get_window_extent(renderer).width
        symbol_width = symbol.get_window_extent(renderer).width
        gap = 0.07 * fig.dpi
        left = (fig.bbox.width - text_width - symbol_width - gap) / 2
        text.set_x((left + symbol_width + gap) / fig.bbox.width)
        symbol.set_xdata([(left + symbol_width / 2) / fig.bbox.width])
    fig._figure1_recipe_rows = list(zip(texts, markers))
    fig._figure1_shared_conditions = shared_text
    add_panel(fig, "a", heading, [sx, shared_text] + texts + markers, row=0, col=0)
    return y - (len(lines) - 1) * step - 0.08


def panel_c(fig, top, bottom):
    heading = fig.text(0, 0, "Shortfall of every hit below 80%")
    P = pd.read_csv(OUT / "posthit_pair_support.csv")
    h = P[(P.m6 >= 0.20) & (P.m6 < 0.80)]
    gap = 100 * (h.b - h.m6)
    severe = int((gap > 20).sum())
    ax = inch_axes(fig, 0.75, bottom, 5.55, top - 0.45 - bottom)
    bins = np.arange(0, 85, 5)
    counts, edges = np.histogram(gap.clip(upper=84.999), bins=bins)
    ax.bar(edges[:-1], counts, width=5, align="edge", color=[ORANGE if e >= 20 else "#BBBBBB" for e in edges[:-1]],
           edgecolor="white", lw=0.4)
    ax.set_xlim(0, 80); ax.set_xticks([0, 20, 40, 60, 80])
    ax.set_xlabel("shortfall to the library's\nbest recipe (yield points)", labelpad=2)
    ax.set_ylabel("hits below 80%")
    ax.tick_params(length=2)
    ax.text(0.97, 0.95, "%d of %d (%.1f%%)\nmore than 20\npoints short" % (severe, len(h), 100 * severe / len(h)),
            transform=ax.transAxes, ha="right", va="top", fontsize=SMALL, color="#8A3B00")
    fig._figure1_cohort = {"hits_below_80": len(h), "severe": severe}
    add_panel(fig, "c", heading, [ax], row=1, col=0)


